PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS Users(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL UNIQUE,
  passwordHash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('Teacher','ResLife')),
  notify INTEGER NOT NULL DEFAULT 0 CHECK (notify IN (0,1))
);

CREATE TABLE IF NOT EXISTS Requests(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  studentId INTEGER NOT NULL REFERENCES Students(id) ON DELETE CASCADE,
  teacherId INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  date TEXT NOT NULL,  -- YYYY-MM-DD
  reason TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','ACK','DONE','CANCEL')),
  createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(studentId, date)
);

CREATE TABLE IF NOT EXISTS Students(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  sid TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  grade INTEGER NOT NULL CHECK (grade BETWEEN 6 AND 12),
  dorm TEXT NOT NULL,
  room TEXT,
  backlog INTEGER NOT NULL DEFAULT 0 CHECK (backlog >= 0),
  updatedAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS AuditLog(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  studentId INTEGER NOT NULL REFERENCES Students(id) ON DELETE CASCADE,
  delta INTEGER NOT NULL,
  oldValue INTEGER NOT NULL,
  newValue INTEGER NOT NULL,
  actor TEXT NOT NULL,  
  ts TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ReleaseLog(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  studentId INTEGER NOT NULL REFERENCES Students(id) ON DELETE CASCADE,
  actor TEXT NOT NULL,
  ts TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Notifications(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  userId INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  studentId INTEGER NOT NULL REFERENCES Students(id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  isRead INTEGER NOT NULL DEFAULT 0 CHECK (isRead IN (0,1)),
  createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Attendance(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  studentId INTEGER NOT NULL REFERENCES Students(id) ON DELETE CASCADE,
  inTs TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  inStaff TEXT NOT NULL,
  isLate INTEGER NOT NULL DEFAULT 0 CHECK (isLate IN (0,1)),
  minutesLate INTEGER NOT NULL DEFAULT 0 CHECK (minutesLate >= 0),
  outTs TEXT,
  outStaff TEXT,
  durationM INTEGER CHECK (durationM IS NULL OR durationM >= 0)
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_unread
ON Notifications(userId, isRead, createdAt);